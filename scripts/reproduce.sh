#!/usr/bin/env bash
# Reproduce the release-gate measurement end to end:
#   corpus -> chunks -> K sampled runs of the baseline and of every frozen regression
#   -> noise report -> gate-v3 experiment (2,000 null releases) -> docs/RESULTS.md
#
#   GENERATOR  model spec (required), e.g. "openai:http://localhost:8001|Qwen/Qwen2.5-7B-Instruct"
#   GOLDEN     frozen test split (default data/golden/frozen/test.jsonl)
#   CHUNKS     chunk file (default: rebuilt from the pinned corpus)
#   K          sampled runs per configuration (default 8; need >= 3 for disjoint null releases)
#   N_SIM      simulated releases per row (default 2000)
set -euo pipefail
cd "$(dirname "$0")/.."
export PYTHONPATH=src
PY="${PY:-.venv/bin/python}"
: "${GENERATOR:?set GENERATOR, e.g. openai:http://localhost:8001|MODEL}"
GOLDEN="${GOLDEN:-data/golden/frozen/test.jsonl}"
K="${K:-8}"; N_SIM="${N_SIM:-2000}"
OUT="${OUT:-data/processed/results}"
RESULTS="${RESULTS:-docs/RESULTS.md}"
mkdir -p "$OUT"

if [[ -z "${CHUNKS:-}" ]]; then
  ./scripts/fetch_corpus.sh
  "$PY" -m gatedrag ingest data/interim/corpus -o data/processed/chunks.jsonl
  CHUNKS=data/processed/chunks.jsonl
fi

MANIFEST="$(dirname "$GOLDEN")/MANIFEST.json"
if [[ -f "$MANIFEST" ]]; then
  "$PY" -m gatedrag golden-check --manifest "$MANIFEST" --chunks "$CHUNKS"   # fails if gold docs changed
fi

echo "== baseline: K=$K runs"
"$PY" -m gatedrag pool --chunks "$CHUNKS" --golden "$GOLDEN" --generator "$GENERATOR" \
  --config configs/release.toml -k "$K" --seed 1 -o "$OUT/pool_baseline.json"
"$PY" -m gatedrag noise "$OUT/pool_baseline.json" > "$OUT/noise.json"

REGS=()
while IFS= read -r line; do
  name="${line%%|*}"; sets="${line#*|}"
  echo "== regression: $name"
  # shellcheck disable=SC2086
  "$PY" -m gatedrag pool --chunks "$CHUNKS" --golden "$GOLDEN" --generator "$GENERATOR" \
    --config configs/release.toml -k "$K" --seed 2 $sets -o "$OUT/pool_$name.json"
  REGS+=(--regression "$name=$OUT/pool_$name.json")
done < <("$PY" - <<'EOF'
import tomllib
regs = tomllib.load(open("configs/regressions.toml", "rb"))["regressions"]
for name, delta in regs.items():
    print(name + "|" + " ".join(f"--set {k}={v}" for k, v in delta.items()))
EOF
)

"$PY" -m gatedrag experiment --rule configs/gate_rule.toml --baseline "$OUT/pool_baseline.json" "${REGS[@]}" \
  --n-sim "$N_SIM" -o "$OUT/gate_experiment"
{
  echo "# Results (generated by scripts/reproduce.sh; do not edit by hand)"
  echo
  echo "Generator: \`$GENERATOR\` | golden: \`$GOLDEN\` | K=$K | null releases: $N_SIM"
  echo
  cat "$OUT/gate_experiment.md"
  echo
  echo "## Measured noise"
  echo
  echo '```json'; cat "$OUT/noise.json"; echo '```'
} > "$RESULTS"
echo "wrote $RESULTS"
